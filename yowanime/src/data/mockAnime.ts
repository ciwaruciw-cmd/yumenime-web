export function isDonghua(anime: Anime): boolean {
  const text = (anime.title + ' ' + (anime.titleEnglish || '') + ' ' + (anime.studio || '')).toLowerCase();
  return (
    text.includes('donghua') ||
    text.includes('chinese') ||
    text.includes('bilibili') ||
    text.includes('tencent')
  );
}

